def write(name, sections):
    text = "".join(f"## {title}\n\n{body.strip()}\n\n" for title, body in sections)
    (OUT / name).write_text(text)
    print(OUT / name, len(sections))


def pods():
    sections, title, lines = [], None, []
    for line in PODS_ACK.read_text().splitlines():
        m = re.match(r"^## (.+)$", line)
        # SwiftProtobuf's license has a "## ... ##" heading of its own.
        if m and not line.rstrip().endswith("##"):
            if title in NATIVE_PODS:
                sections.append((title, "\n".join(lines)))
            title, lines = m.group(1).strip(), []
        elif title:
            lines.append(line.replace("## ", "") if line.startswith("## ") else line)
    if title in NATIVE_PODS:
        sections.append((title, "\n".join(lines)))
    return [(t, re.sub(r"\nGenerated by CocoaPods.*", "", b, flags=re.S)) for t, b in sections]


